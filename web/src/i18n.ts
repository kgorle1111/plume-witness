export const STRINGS: Record<Lang, Record<StringKey, string>> = { en: EN, es: ES }

export type Vars = Record<string, string | number>

/** Fills `{name}` slots. A slot with no value is left visible so a typo shows up in review, not as a blank. */
export function fmt(template: string, vars?: Vars): string {
  return vars ? template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : template
}

export function translate(lang: Lang, key: StringKey, vars?: Vars): string {
  return fmt(STRINGS[lang][key], vars)
}

// ---- language setting ----

const STORAGE_KEY = 'pw-lang'

/** Saved choice first; otherwise Spanish only when the browser says so. Storage can throw (private windows, blocked data). */
export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'en' || saved === 'es') return saved
  } catch { /* fall through to the browser language */ }
  try {
    if (typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('es')) return 'es'
  } catch { /* default */ }
  return 'en'
}

let current: Lang = detectLang()
try { document.documentElement.lang = current } catch { /* no document (tests) */ }
const listeners = new Set<() => void>()

export const getLang = (): Lang => current
export const subscribeLang = (fn: () => void): (() => void) => {
  listeners.add(fn)
  return () => { listeners.delete(fn) }
}

export function setLang(l: Lang): void {
  if (l === current) return
  current = l
  try { localStorage.setItem(STORAGE_KEY, l) } catch { /* a choice that cannot be saved still applies this visit */ }
  try { document.documentElement.lang = l } catch { /* no document (tests) */ }
  for (const fn of listeners) fn()
}

// ---- dates ----

const LOCALE: Record<Lang, string> = { en: 'en-US', es: 'es-US' }

/** ISO date (YYYY-MM-DD) as text. UTC on both sides, so the day never shifts with the reader's time zone. */
export function dateLabel(iso: string, lang: Lang): string {
  const [y, m, d] = iso.split('-').map(Number)
  return new Intl.DateTimeFormat(LOCALE[lang], { timeZone: 'UTC', year: 'numeric', month: 'short', day: 'numeric' }).format(Date.UTC(y, m - 1, d))
}

/** Month 0 is January 2024, as in rain.ts. */
export function monthYearLabel(m: number, lang: Lang): string {
  return new Intl.DateTimeFormat(LOCALE[lang], { timeZone: 'UTC', year: 'numeric', month: 'long' }).format(Date.UTC(2024, m, 1))
}

/** Short month name for a 0-11 index ("Jan", "ene"), without a trailing period. */
export function monthShort(i: number, lang: Lang): string {
  return new Intl.DateTimeFormat(LOCALE[lang], { timeZone: 'UTC', month: 'short' }).format(Date.UTC(2024, i, 1)).replace(/\.$/, '')
}

